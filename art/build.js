#!/usr/bin/env node
// Builds every icon.  Usage: node art/build.js [--only <keyPrefix>] [--sheet <keyPrefix>]
//   outputs: assets/icons/<key>.svg  (styled, full colour, shown with <img>)
//            source/0_sprite.html    (flat icons as <symbol>s, inlined in index.html, tinted with currentColor)
//            source/0_icons_gen.js   (key lists for the runtime)
//   --sheet <prefix> also writes art/out/sheet-<prefix>.png — a contact sheet to eyeball your work
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const L = require('./lib');

const args = process.argv.slice(2);
const only = args.includes('--only') ? args[args.indexOf('--only') + 1] : null;
const sheet = args.includes('--sheet') ? args[args.indexOf('--sheet') + 1] : null;
const OUT = path.join(L.ROOT, 'assets', 'icons');
fs.mkdirSync(OUT, { recursive: true });

// ---------------------------------------------------------------- styled icons
const recipes = []; let errors = 0, badFile = false;
for (const f of fs.readdirSync(path.join(__dirname, 'recipes')).filter(f => f.endsWith('.js')).sort()) {
  let list; try { list = require(path.join(__dirname, 'recipes', f)); } catch (e) { console.error(`RECIPE FILE ${f} failed to load: ${e.message}`); errors++; badFile = true; continue; }
  for (const r of list) { r._file = f; recipes.push(r); }
}
const styled = []; const seen = new Map();
for (const r of recipes) {
  const keys = r.tiered ? [1, 2, 3, 4, 5, 6].map(t => [`${r.key}-t${t}`, t]) : [[r.key, r.tier || 4]];
  for (const [key, t] of keys) {
    if (seen.has(key)) { console.error(`DUPLICATE styled key ${key} (${seen.get(key)} and ${r._file})`); errors++; continue; }
    seen.set(key, r._file); styled.push(key);
    if (only && !key.startsWith(only)) continue;
    try {
      const c = L.makeCtx(r.base, t, { roles: r.roles, fx: r.fx });
      const parts = r.draw(c) || {};
      fs.writeFileSync(path.join(OUT, key + '.svg'), L.finish(c, typeof parts === 'string' ? { body: parts } : parts));
    } catch (e) { console.error(`ERROR in ${r._file} ${key}: ${e.stack.split('\n').slice(0, 3).join(' ')}`); errors++; }
  }
}
if (!only && !badFile) for (const f of fs.readdirSync(OUT)) if (f.endsWith('.svg') && !seen.has(f.slice(0, -4))) fs.unlinkSync(path.join(OUT, f)); // drop stale

// ---------------------------------------------------------------- flat icons
const flat = {}; const flatFrom = {};
for (const f of fs.readdirSync(path.join(__dirname, 'flat')).filter(f => f.endsWith('.json')).sort()) {
  const m = JSON.parse(fs.readFileSync(path.join(__dirname, 'flat', f), 'utf8'));
  for (const k in m) {
    if (k.startsWith('_')) continue;
    if (flat[k] && flat[k] !== m[k]) { console.error(`FLAT key "${k}" defined twice with different icons: ${flatFrom[k]}=${flat[k]} vs ${f}=${m[k]}`); errors++; continue; }
    if (seen.has(k)) { console.error(`FLAT key "${k}" (${f}) clashes with a styled icon`); errors++; }
    flat[k] = m[k]; flatFrom[k] = f;
  }
}
const syms = [];
for (const k of Object.keys(flat).sort()) {
  try { L.loadGI(flat[k]); const raw = fs.readFileSync(path.join(L.GI_CACHE, flat[k] + '.svg'), 'utf8');
    const ds = [...raw.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map(m => m[1]).filter(d => d.trim() !== 'M0 0h512v512H0z');
    syms.push(`<symbol id="i-${k}" viewBox="0 0 512 512">${ds.map(d => `<path d="${d}"/>`).join('')}</symbol>`);
  } catch (e) { console.error(`FLAT ${k} (${flatFrom[k]}): ${e.message}`); errors++; }
}
fs.writeFileSync(path.join(L.ROOT, 'source', '0_sprite.html'), `<svg xmlns="http://www.w3.org/2000/svg" style="position:absolute;width:0;height:0;overflow:hidden" aria-hidden="true"><defs>${syms.join('')}</defs></svg>\n`);
fs.writeFileSync(path.join(L.ROOT, 'source', '0_icons_gen.js'), `// GENERATED by art/build.js — do not edit\nconst ICON_STYLED = new Set(${JSON.stringify(styled)});\nconst ICON_FLAT = new Set(${JSON.stringify(Object.keys(flat).sort())});\nconst RAR_TIER = ${JSON.stringify(L.RAR_TIER)};\n`);

// ---------------------------------------------------------------- contact sheet
if (sheet) {
  const ks = styled.filter(k => k.startsWith(sheet)).concat(Object.keys(flat).filter(k => k.startsWith(sheet)).map(k => '#' + k));
  const cols = 6, cell = 150, rows = Math.ceil(ks.length / cols);
  const body = ks.map((k, i) => { const x = (i % cols) * cell, y = Math.floor(i / cols) * cell;
    const img = k[0] === '#' ? `<g transform="translate(${x + 27} ${y + 12}) scale(${96 / 512})" fill="#e8d9b0"><path d="${L.fmt(L.loadGI(flat[k.slice(1)]))}"/></g>`
      : (() => { const raw = fs.readFileSync(path.join(OUT, k + '.svg'), 'utf8').replace(/id="([^"]+)"/g, `id="k${i}_$1"`).replace(/url\(#([^)]+)\)/g, `url(#k${i}_$1)`);
          return raw.replace('<svg ', `<svg x="${x + 15}" y="${y + 4}" width="120" height="120" `); })();
    return `<rect x="${x + 4}" y="${y + 4}" width="${cell - 8}" height="${cell - 8}" rx="12" fill="#181520" stroke="#3a3346"/>${img}<text x="${x + cell / 2}" y="${y + cell - 10}" fill="#bbb" font-size="12" font-family="sans-serif" text-anchor="middle">${k.replace('#', '')}</text>`; }).join('');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${cols * cell}" height="${rows * cell}"><rect width="100%" height="100%" fill="#0c0a10"/>${body}</svg>`;
  fs.mkdirSync(path.join(__dirname, 'out'), { recursive: true });
  const sp = path.join(__dirname, 'out', `sheet-${sheet}.svg`), pp = sp.replace(/\.svg$/, '.png');
  fs.writeFileSync(sp, svg); execFileSync('rsvg-convert', ['-o', pp, sp]); console.log('sheet:', pp);
}
console.log(`styled: ${styled.length}  flat: ${Object.keys(flat).length}  errors: ${errors}`);
process.exit(errors ? 1 : 0);
